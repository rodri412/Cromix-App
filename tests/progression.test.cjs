const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const { PGlite } = require('@electric-sql/pglite');
test('Onboarding, unlocks and daily envelopes are enforced by PostgreSQL', async t => {
  const db = new PGlite(); t.after(()=>db.close());
  const a='00000000-0000-0000-0000-000000000001',b='00000000-0000-0000-0000-000000000002',c='00000000-0000-0000-0000-000000000003';
  const owner='e4142db2-3668-4b21-93f7-67d11eea63dd';
  const track='0123456789ABCDEFGHIJKL';
  await db.exec(`create role anon; create role authenticated; create role service_role bypassrls; create schema auth;
    create table auth.users(id uuid primary key,raw_user_meta_data jsonb);
    create function auth.uid() returns uuid language sql stable as $$select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid$$;
    create function auth.role() returns text language sql stable as $$select current_setting('request.jwt.claim.role',true)$$;
    grant usage on schema auth to authenticated,service_role;
    insert into auth.users values('${a}','{}'),('${b}','{}'),('${c}','{}'),('${owner}','{}');`);
  await db.exec(fs.readFileSync('supabase/migrations/202610030001_cromix.sql','utf8'));
  await db.exec(`insert into perfiles(id,username) values('${a}','alice'),('${b}','bob'),('${c}','carol'),('${owner}','creator_test'); insert into amigos(user_id,friend_id) values('${a}','${b}');
    alter table mixtapes disable trigger cromix_guard_gift;
    insert into mixtapes(sender_id,receiver_id,track_name,artist_name,message,created_at) select '${b}','${a}','Recuerdo '||i,'Artista','Para ti','2020-01-01' from generate_series(1,60) i;
    alter table mixtapes enable trigger cromix_guard_gift;`);
  await db.exec(fs.readFileSync('supabase/migrations/202610030002_shared_shelves.sql','utf8'));
  await db.exec(fs.readFileSync('supabase/migrations/202610030003_progression.sql','utf8'));
  await db.exec(fs.readFileSync('supabase/migrations/202610030004_backend_permissions.sql','utf8'));
  await db.exec(fs.readFileSync('supabase/migrations/202610030005_creator_daily.sql','utf8'));
  await db.exec(fs.readFileSync('supabase/migrations/202610040001_owner_self_friend.sql','utf8'));
  const actor=async (id,role='authenticated')=>{await db.exec('reset role');await db.query("select set_config('request.jwt.claim.sub',$1,false),set_config('request.jwt.claim.role',$2,false)",[id,role]);await db.exec('set role '+role);};
  const progress=async()=> (await db.query('select get_music_progress() as p')).rows[0].p;
  const artist=n=>({id:String(n).padStart(22,'0'),name:'Artist '+n,imageUrl:null,externalUrl:'https://open.spotify.com/artist/'+String(n).padStart(22,'0')});
  const artists=[artist(1),artist(2),artist(3)];
  const save=async values=>db.query('select save_music_artists($1,$2::jsonb) as p',[a,JSON.stringify(values)]);
  await t.test('Three different artists are mandatory; clients cannot forge preferences or progress',async()=>{
    await actor(a); let p=await progress(); assert.equal(p.level,1);assert.equal(p.slots,3);assert.equal(p.onboarded,false);
    await assert.rejects(save(artists),/permission denied/);
    await assert.rejects(db.query('insert into music_preferences(user_id,artists) values($1,$2)',[a,JSON.stringify(artists)]),/permission denied/);
    await assert.rejects(db.query('select cromix_progress($1)',[b]),/permission denied/);
    await actor('', 'service_role');
    await assert.rejects(save([artist(1),artist(1),artist(2)]),/distintos/);
    await assert.rejects(save([...artists,artist(4)]),/exactamente 3/);
    await save(artists);
    assert.equal((await db.query('select artists from music_preferences where user_id=$1',[a])).rows[0].artists.length,3);
    assert.equal((await db.query('select gift_id from daily_gifts where user_id=$1',[a])).rows.length,0);
    await assert.rejects(save([...artists,artist(4)]),/Sube de nivel/);
    await actor(c);assert.equal((await db.query('select * from music_preferences')).rows.length,0);
  });
  await t.test('Sending three gifts unlocks the fourth artist, then ten opened pieces unlock the fifth',async()=>{
    await actor(a);
    for(let i=0;i<3;i++) await db.query(`select send_mixtape('bob','Canción','Artista',null,$1,$2,'CD','kraft','Hola',null)`,[track,'https://open.spotify.com/track/'+track]);
    let p=await progress();assert.equal(p.level,2);assert.equal(p.slots,4);
    await actor('','service_role');await save([...artists,artist(4)]);
    await assert.rejects(save([artist(8),artist(2),artist(3),artist(4)]),/cambio/);
    await assert.rejects(save(artists),/Conserva/);
    await actor(a);await db.query("update mixtapes set opened=true where id in (select id from mixtapes where receiver_id=$1 order by track_name limit 10)",[a]);
    p=await progress();assert.equal(p.level,3);assert.equal(p.slots,5);assert.equal(p.pieces,10);assert.equal(p.changesAvailable,0);
    await actor('','service_role');await save([...artists,artist(4),artist(5)]);
  });
  await t.test('Later levels award artist changes, consumed exactly once',async()=>{
    await actor(a);await db.query('update mixtapes set opened=true where receiver_id=$1',[a]);
    let p=await progress();assert.equal(p.level,4);assert.equal(p.changesAvailable,1);
    await actor('','service_role');const changed=[artist(6),artist(2),artist(3),artist(4),artist(5)];
    await save(changed);await save([...changed].reverse());
    await assert.rejects(save([artist(7),artist(2),artist(3),artist(4),artist(5)]),/cambio/);
    await actor(a);p=await progress();assert.equal(p.changesAvailable,0);assert.equal(p.artists.length,5);
  });
  await t.test('Daily gifts are server-only, once per UTC day and separate from friend sends',async()=>{
    const payload={id:track,name:'Canción diaria',artist:'Artist 6',albumUrl:null,externalUrl:'https://open.spotify.com/track/'+track};
    const day=new Date().toISOString().slice(0,10),artistId=artist(6).id;
    const issue=async(format='VINILO')=>db.query('select issue_daily_gift($1,$2::jsonb,$3,$4,$5,$6) as id',[a,JSON.stringify(payload),format,artistId,artistId+':cancion diaria',day]);
    await actor(a);await assert.rejects(issue(),/permission denied/);
    await assert.rejects(db.query(`insert into mixtapes(sender_id,receiver_id,track_name,artist_name,message,origin) values($1,$2,'Fake','Artista','Hola','daily')`,[a,b]),/servidor/);
    await actor('','service_role');const first=(await issue()).rows[0].id;assert.equal((await issue('CD')).rows[0].id,first);
    assert.equal((await db.query('select gift_id from daily_gifts where user_id=$1',[a])).rows[0].gift_id,first);
    await actor(a);let p=await progress();assert.equal(p.dailyGiftId,first);assert.equal(p.sent,3);assert.equal(p.pieces,60);
    await db.query('update mixtapes set opened=true where id=$1',[first]);p=await progress();assert.equal(p.pieces,61);assert.equal(p.sent,3);
    await actor(c);assert.equal((await db.query('select * from daily_gifts')).rows.length,0);
    assert.equal((await db.query('select id from mixtapes where id=$1',[first])).rows.length,0);
    await actor('','service_role');await assert.rejects(db.query('select issue_daily_gift($1,$2::jsonb,$3,$4,$5,$6)',[c,JSON.stringify(payload),'CD',artistId,'song','2000-01-01']),/día cambió/);
  });
  await t.test('Creator quota is tied to an immutable account ID and cannot be claimed by renaming',async()=>{
    await actor(a);await assert.rejects(db.query('insert into creator_accounts(user_id) values($1)',[a]),/permission denied/);
    await actor('','service_role');await assert.rejects(db.query('insert into creator_accounts(user_id) values($1)',[a]),/permission denied/);
    await db.exec('reset role');await db.query('insert into creator_accounts(user_id) values($1)',[a]);
    await actor(a);await db.query("update perfiles set username='alice_new' where id=$1",[a]);assert.equal((await progress()).dailyUnlimited,true);
    await actor(c);await db.query("update perfiles set username='rodri412' where id=$1",[c]);assert.equal((await progress()).dailyUnlimited,false);
    await actor('','service_role');
    const payload={id:track,name:'Otra canción',artist:'Artist 6',albumUrl:null};
    const args=[a,JSON.stringify(payload),'CD',artist(6).id,'another-song',new Date().toISOString().slice(0,10)];
    const one=(await db.query('select issue_daily_gift($1,$2::jsonb,$3,$4,$5,$6) as id',args)).rows[0].id;
    const two=(await db.query('select issue_daily_gift($1,$2::jsonb,$3,$4,$5,$6) as id',args)).rows[0].id;
    assert.notEqual(one,two);
    await actor(a);assert.equal((await progress()).dailyGiftId,two);
  });
  await t.test('Only the pinned owner can find and add themselves, even after changing username',async()=>{
    await actor(c);assert.equal((await progress()).canAddSelf,false);
    assert.equal((await db.query('select can_add_self() as allowed')).rows[0].allowed,false);
    await assert.rejects(db.query('insert into amigos(user_id,friend_id) values($1,$1)',[c]),/row-level security/);
    await actor(a);assert.equal((await progress()).canAddSelf,false,'A creator-table entry alone does not grant this owner capability');
    await assert.rejects(db.query('insert into amigos(user_id,friend_id) values($1,$1)',[a]),/row-level security/);
    await actor(owner);
    let p=await progress();assert.equal(p.canAddSelf,true);assert.equal(p.dailyUnlimited,true);
    await db.query("update perfiles set username='owner_renamed' where id=$1",[owner]);
    assert.equal((await progress()).canAddSelf,true);
    assert.equal((await db.query("select id from perfiles where username ilike '%owner_renamed%'")).rows[0].id,owner);
    await db.query('insert into amigos(user_id,friend_id) values($1,$1)',[owner]);
    assert.ok((await db.query('select friend_id from amigos')).rows.some(row=>row.friend_id===owner));
    await assert.rejects(db.query('insert into amigos(user_id,friend_id) values($1,$1)',[c]),/row-level security/);
    await assert.rejects(db.query('insert into creator_accounts(user_id) values($1)',[c]),/permission denied/);
  });
  await t.test('Owner self-gifts keep the normal send quota and cannot fabricate sent-achievement progress',async()=>{
    await actor(owner);
    for(let i=0;i<3;i++) await db.query(`select send_mixtape('owner_renamed','Canción','Artista',null,$1,$2,'CD','kraft','Para probar',null)`,[track,'https://open.spotify.com/track/'+track]);
    assert.equal((await progress()).sent,0);
    await assert.rejects(db.query(`select send_mixtape('owner_renamed','Canción','Artista',null,$1,$2,'CD','kraft','Para probar',null)`,[track,'https://open.spotify.com/track/'+track]),/tres envíos/);
    await actor(c);
    await assert.rejects(db.query(`select send_mixtape('rodri412','Canción','Artista',null,$1,$2,'CD','kraft','Hola',null)`,[track,'https://open.spotify.com/track/'+track]),/Elige a un amigo/);
  });
});
